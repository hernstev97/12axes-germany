/**
 * Build-only projection of the reviewed public v2.2 exports (data/reference-v2.2/*.json).
 * Reads aggregate public files only. Withheld or unreviewed references carry no numbers.
 *   node web/src/app/policy-draft/generate-references-v22.mjs          # write
 *   node web/src/app/policy-draft/generate-references-v22.mjs --check  # verify
 */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { format } from 'prettier';

const repository = new URL('../../../../', import.meta.url);
const output = new URL('./reviewed-references-v22.ts', import.meta.url);
const studies = ['ESS5e03_6', 'ESS8e02_3', 'ESS9e03_3', 'ESS10SCe03_2', 'ESS11e04_2'];
const REVIEWED = 'reviewed_historical_reference';

function projectReference(reference) {
  if (reference === null) return null;
  return {
    validCount: reference.validCount,
    totalCount: reference.totalCount,
    missingCount: reference.missingCount,
    notAskedCount: reference.notAskedCount,
    categories: reference.categories.map((category) => ({
      code: category.code,
      proportion: category.proportion,
      lower: category.lower,
      upper: category.upper,
    })),
    interval: reference.interval
      ? {
          degreesOfFreedom: reference.interval.degreesOfFreedom,
          strata: reference.interval.strata,
          psus: reference.interval.psus,
        }
      : null,
  };
}

const sources = {};
const projected = studies.map((study) => {
  const path = `data/reference-v2.2/${study}.json`;
  const bytes = readFileSync(new URL(path, repository));
  sources[path] = createHash('sha256').update(bytes).digest('hex');
  const document = JSON.parse(bytes.toString('utf8'));
  assert.equal(document.study, study);
  for (const question of document.questions) {
    assert.equal(question.reference !== null, question.status === REVIEWED);
  }
  return {
    study,
    designAvailable: document.designAvailable,
    questions: document.questions.map((question) => ({
      id: question.id,
      status: question.status,
      reference: projectReference(question.reference),
    })),
    groups: document.groups.map((group) => ({
      groupId: group.groupId,
      pairs: group.pairs.map((pair) => ({
        questionId: pair.questionId,
        status: pair.status,
        reference: projectReference(pair.reference),
      })),
    })),
  };
});

const text = await format(
  `// Aggregates from ESS ERIC / Sikt data (CC BY-NC-SA 4.0), computed by this project.
// Generated by generate-references-v22.mjs from reviewed exports. Do not edit by hand.
import type { ReferencesV22 } from './reference-v22';

export const REVIEWED_REFERENCES_V22: ReferencesV22 = ${JSON.stringify({ sources, studies: projected })};
`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);

if (process.argv.includes('--check')) {
  assert.equal(readFileSync(output, 'utf8'), text, 'reviewed-references-v22.ts is not current');
  console.log('PASS: reviewed-references-v22.ts matches data/reference-v2.2.');
} else {
  writeFileSync(output, text);
  console.log('Wrote reviewed-references-v22.ts from data/reference-v2.2.');
}
